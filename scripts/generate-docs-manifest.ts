import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const componentsDirectory = join(scriptDirectory, "..", "content", "components");
const blocksDirectory = join(scriptDirectory, "..", "content", "blocks");
const componentSlugs = readdirSync(componentsDirectory)
  .filter((fileName) => fileName.endsWith(".mdx"))
  .map((fileName) => fileName.replace(/\.mdx$/, ""))
  .sort((left, right) => left.localeCompare(right));

const metadataImports = componentSlugs
  .map(
    (slug) =>
      `import { metadata as ${toCamelCase(slug)}Metadata } from "@/content/components/${slug}.mdx";`,
  )
  .join("\n");

const documents = componentSlugs
  .map((slug) => `  defineComponentDoc("${slug}", ${toCamelCase(slug)}Metadata),`)
  .join("\n");

const contentLoaders = componentSlugs
  .map((slug) => `  "${slug}": () => import("@/content/components/${slug}.mdx"),`)
  .join("\n");

const source = `// Generated by bun run docs:manifest. Do not edit directly.

import type { ComponentType } from "react";

${metadataImports}
import { defineComponentDoc, type ComponentDoc } from "@/content/components/schema";

const componentDocs = [
${documents}
] as const satisfies readonly ComponentDoc[];

type ComponentSlug = (typeof componentDocs)[number]["slug"];

const componentContentLoaders = {
${contentLoaders}
} satisfies Record<ComponentSlug, () => Promise<{ default: ComponentType }>>;

function getComponentDoc(slug: string) {
  return componentDocs.find((component) => component.slug === slug);
}

async function getComponentContent(slug: ComponentSlug) {
  const componentModule = await componentContentLoaders[slug]();
  return componentModule.default;
}

export type { ComponentSlug };
export { componentDocs, getComponentContent, getComponentDoc };
`;

writeFileSync(join(componentsDirectory, "index.ts"), source);

const blockSlugs = readdirSync(blocksDirectory)
  .filter((fileName) => fileName.endsWith(".mdx"))
  .map((fileName) => fileName.replace(/\.mdx$/, ""))
  .sort((left, right) => left.localeCompare(right));

const blockMetadataImports = blockSlugs
  .map(
    (slug) =>
      `import { metadata as ${toCamelCase(slug)}Metadata } from "@/content/blocks/${slug}.mdx";`,
  )
  .join("\n");

const blockDocuments = blockSlugs
  .map((slug) => `  defineBlockDoc("${slug}", ${toCamelCase(slug)}Metadata),`)
  .join("\n");

const blockContentLoaders = blockSlugs
  .map((slug) => `  "${slug}": () => import("@/content/blocks/${slug}.mdx"),`)
  .join("\n");

const blockSource = `// Generated by bun run docs:manifest. Do not edit directly.

import type { ComponentType } from "react";

${blockMetadataImports}
import { defineBlockDoc, type BlockDoc } from "@/content/blocks/schema";

const blockDocs = [
${blockDocuments}
] as const satisfies readonly BlockDoc[];

type BlockSlug = (typeof blockDocs)[number]["slug"];

const blockContentLoaders = {
${blockContentLoaders}
} satisfies Record<BlockSlug, () => Promise<{ default: ComponentType }>>;

function getBlockDoc(slug: string) {
  return blockDocs.find((block) => block.slug === slug);
}

async function getBlockContent(slug: BlockSlug) {
  const blockModule = await blockContentLoaders[slug]();
  return blockModule.default;
}

export type { BlockSlug };
export { blockDocs, getBlockContent, getBlockDoc };
`;

writeFileSync(join(blocksDirectory, "index.ts"), blockSource);

function toCamelCase(value: string) {
  return value.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase());
}
